// Bundles the guided reading and listening units into comprehension-data.js, which comprehension.js loads on first use,
// and writes the unit count per skill into lang-profile.js (a skill's tab stays hidden while it has no units).
// Sources: scripts/comprehension/<level>.json (hsk1.json … hsk7-9.json), one array of units per level, authored by hand;
// a missing or empty file means no units at that level. A unit (German prose, Chinese only in passages and glossary):
//   { id: 'reading-hsk1-01', level: 'HSK1', skill: 'reading' | 'listening', order: 1, title, objective,
//     task: { no, title } (scripts/hsk2025/tasks.json), topic: 'tier1›tier2›tier3', textType, minutes, introduction,
//     passages: [{ id: 'p1', speaker: 'A' | 'B' | '', label?, text, pinyin }], translation,
//     glossary: [{ word, pinyin, meaning, vocabId? }], note,
//     questions: [{ id: 'q1', kind, prompt, evidence: 'p1', choices: [{ text, explanation }], answer }], audio?: { src, revision } }
// scripts/audit-comprehension.cjs checks them.
// Usage: node scripts/build-comprehension.cjs [--check]
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(__dirname, 'comprehension');
const PROFILE_FILE = 'lang-profile.js';
const SKILLS = ['reading', 'listening'];
const HEADER = '// Generated by scripts/build-comprehension.cjs from scripts/comprehension/<level>.json. Do not edit; run npm run build:comprehension.\n';
const PROFILE_COUNTS = /(comprehension: \{ data: '[^']+', )reading: \d+, listening: \d+( \})/;

const readRoot = file => fs.readFileSync(path.join(ROOT, file), 'utf8').replace(/\r\n/g, '\n');

function loadProfile(profileText) {
  const context = {};
  context.window = context;
  vm.runInNewContext(profileText, context, { filename: PROFILE_FILE });
  return context.LANG_PROFILE;
}

const sourceFile = level => path.join(SOURCE_DIR, level.toLowerCase() + '.json');

// One entry per level: { level, file, units }; throws on unreadable JSON or a non-array.
function loadSources(levels, readSource = file => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null)) {
  return levels.map(level => {
    const file = sourceFile(level);
    const text = readSource(file);
    const rel = path.relative(ROOT, file).replace(/\\/g, '/');
    if (text === null || !text.trim()) return { level, file: rel, units: [] };
    let units;
    try { units = JSON.parse(text.replace(/^﻿/, '')); } catch (e) { throw new Error(rel + ': ' + e.message); }
    if (!Array.isArray(units)) throw new Error(rel + ': expected an array of units');
    return { level, file: rel, units };
  });
}

// Level order, reading before listening, then the authored order.
function collect(sources) {
  return sources.flatMap((source, levelIndex) => source.units.map((unit, i) => ({ unit, levelIndex, i })))
    .sort((a, b) => a.levelIndex - b.levelIndex || SKILLS.indexOf(a.unit.skill) - SKILLS.indexOf(b.unit.skill) ||
      (a.unit.order || 0) - (b.unit.order || 0) || a.i - b.i)
    .map(entry => entry.unit);
}

// One unit per line keeps git diffs readable; the revision changes with any content change.
function bundle(units) {
  const revision = crypto.createHash('sha256').update(JSON.stringify(units)).digest('hex').slice(0, 12);
  return HEADER + 'window.COMPREHENSION_DATA = {\n"revision": "' + revision + '",\n"units": [\n' +
    units.map(unit => JSON.stringify(unit)).join(',\n') + (units.length ? '\n' : '') + ']};\n';
}

function withCounts(profileText, counts) {
  if (!PROFILE_COUNTS.test(profileText)) throw new Error(PROFILE_FILE + ': comprehension counts line not found');
  return profileText.replace(PROFILE_COUNTS, '$1reading: ' + counts.reading + ', listening: ' + counts.listening + '$2');
}

function buildComprehension(readFile = readRoot, readSource) {
  const profileText = readFile(PROFILE_FILE);
  const profile = loadProfile(profileText);
  const units = collect(loadSources(profile.levels, readSource));
  const counts = {};
  for (const skill of SKILLS) counts[skill] = units.filter(unit => unit.skill === skill).length;
  return { [profile.comprehension.data]: bundle(units), [PROFILE_FILE]: withCounts(profileText, counts) };
}

// A Windows checkout (core.autocrlf) may hold the files with CRLF line endings.
function staleFiles(files) {
  return Object.keys(files).filter(file => {
    const target = path.join(ROOT, file);
    return !fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== files[file];
  });
}

function main(args) {
  const files = buildComprehension();
  const stale = staleFiles(files);
  if (args.includes('--check')) {
    if (stale.length) {
      console.error('Stale comprehension bundle: ' + stale.join(', ') + '. Run npm run build:comprehension.');
      process.exit(1);
    }
    console.log('Comprehension bundle is up to date (' + Object.keys(files).join(', ') + ').');
    return;
  }
  for (const file of stale) fs.writeFileSync(path.join(ROOT, file), files[file]);
  console.log(stale.length ? 'Wrote ' + stale.join(', ') : 'Comprehension bundle already up to date.');
}

if (require.main === module) {
  try { main(process.argv.slice(2)); } catch (error) { console.error(error.message); process.exit(1); }
}
module.exports = { SKILLS, SOURCE_DIR, loadProfile, loadSources, collect, bundle, withCounts, buildComprehension, staleFiles, sourceFile };
