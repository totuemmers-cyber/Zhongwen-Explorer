// Writes scripts/grammar/STATUS.md: grammar enrichment progress per level.
const fs = require('fs');
const path = require('path');
const enrich = require('../enrich/common.cjs');
const grammar = require('./common.cjs');

const rows = {};
for (const entry of grammar.loadGrammar()) {
  const row = rows[entry.level] = rows[entry.level] || { total: 0, reviewed: 0, withReviewer: 0, quiz: 0 };
  row.total++;
  if (entry.review) row.reviewed++;
  if (entry.review && entry.review.policy === 'author+review') row.withReviewer++;
  if (entry.quiz) row.quiz++;
}
const order = grammar.LEVELS.filter(level => rows[level]);
const total = order.reduce((n, l) => n + rows[l].total, 0);
const done = order.reduce((n, l) => n + rows[l].reviewed, 0);
const ledger = enrich.readJson(path.join(__dirname, 'ledger.json'), {});
const md = [
  '# Grammar enrichment status',
  '',
  'Generated by `scripts/grammar/status.cjs`. ' + done + ' of ' + total + ' grammar points enriched (' + (100 * done / total).toFixed(1) + ' %), ' +
    new Set(Object.values(ledger).map(e => e.batch)).size + ' batches applied.',
  '',
  '| Level | Points | Enriched | with 2nd reviewer | with quiz |',
  '|---|---|---|---|---|',
  ...order.map(l => '| ' + l + ' | ' + rows[l].total + ' | ' + rows[l].reviewed + ' | ' + rows[l].withReviewer + ' | ' + rows[l].quiz + ' |'),
  ''
].join('\n');
fs.writeFileSync(path.join(__dirname, 'STATUS.md'), md);
console.log(md);
