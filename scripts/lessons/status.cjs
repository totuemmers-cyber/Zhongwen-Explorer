// Writes scripts/lessons/STATUS.md: lessons per level, ledger state, proposals done/open, open batches and the
// share of grammar points linked by a lesson.
const fs = require('fs');
const path = require('path');
const enrich = require('../enrich/common.cjs');
const grammarCommon = require('../grammar/common.cjs');
const L = require('./common.cjs');

const lessons = L.loadLessons();
const ledger = L.readJson(L.LEDGER, {});
const proposals = require('./proposals.json').lessons;
const open = enrich.readJson(path.join(enrich.WORK, 'open-batches.json'), {});
const openLessons = Object.entries(open).filter(([b]) => /^l\d{3}$/.test(b));
const ids = new Set(lessons.map(l => l.id));

const byLevel = {};
for (const l of lessons) {
  const row = byLevel[l.level] = byLevel[l.level] || { total: 0, baseline: 0, authored: 0, unchanged: 0 };
  row.total++;
  const entry = ledger[l.id];
  if (entry && entry.batch === 'baseline') row.baseline++; else if (entry) row.authored++;
  if (entry && entry.hash === L.contentHash(l)) row.unchanged++;
}
const groups = {};
for (const p of proposals) {
  const g = groups[p.group] = groups[p.group] || { total: 0, planned: 0, done: 0, inBatch: 0 };
  g.total++;
  if (p.id) g.planned++;
  if (p.id && ids.has(p.id)) g.done++;
  if (p.id && openLessons.some(([, list]) => list.includes(p.id))) g.inBatch++;
}
const points = grammarCommon.loadGrammar();
const linked = new Set(lessons.flatMap(l => l.grammarIds || []));
const levels = ['HSK1', 'HSK2', 'HSK3', 'HSK4', 'HSK5', 'HSK6', 'HSK7-9'];
const md = [
  '# Grammar lessons status',
  '',
  'Generated by `scripts/lessons/status.cjs`. ' + lessons.length + ' lessons in grammar-lessons.js; ' +
    Object.keys(ledger).length + ' ledger entries (' + new Set(Object.values(ledger).map(e => e.batch)).size + ' batches incl. baseline).',
  '',
  '| Level | Lessons | baseline | authored | unchanged since ledger |',
  '|---|---|---|---|---|',
  ...L.ENGINE_LEVELS.filter(l => byLevel[l]).map(l => '| ' + l + ' | ' + byLevel[l].total + ' | ' + byLevel[l].baseline + ' | ' + byLevel[l].authored + ' | ' + byLevel[l].unchanged + ' |'),
  '',
  '## Proposals (scripts/lessons/proposals.json)',
  '',
  '| Group | Proposed | with id (planned) | in an open batch | applied |',
  '|---|---|---|---|---|',
  ...Object.entries(groups).map(([g, r]) => '| ' + g + ' | ' + r.total + ' | ' + r.planned + ' | ' + r.inBatch + ' | ' + r.done + ' |'),
  '',
  '## Open batches',
  '',
  ...(openLessons.length ? openLessons.map(([b, list]) => '- ' + b + ': ' + list.join(', ')) : ['- none']),
  '',
  '## Grammar points linked by a lesson',
  '',
  '| Level | Points | linked |',
  '|---|---|---|',
  ...levels.map(level => { const all = points.filter(p => p.level === level); const n = all.filter(p => linked.has(p.id)).length; return '| ' + level + ' | ' + all.length + ' | ' + n + ' (' + Math.round(100 * n / all.length) + ' %) |'; }),
  ''
].join('\n');
fs.writeFileSync(path.join(__dirname, 'STATUS.md'), md);
console.log(md);
