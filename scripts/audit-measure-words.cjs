// Audit of the Zählwörter data (measure-words-data.js, built by scripts/measure-words/build.cjs):
// ids, levels, kinds, categories (filter options in index.html), links to vocabulary (nouns, vocabId, removed),
// examples that use the classifier, German without ASCII umlauts, and every classifier vocab.measureWords uses.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const common = require('./enrich/common.cjs');
const { asciiUmlauts } = require('./hanzi/common.cjs');

const ROOT = path.resolve(__dirname, '..');
const profile = common.loadProfile();
const context = { console };
context.window = context;
for (const file of profile.dataScripts.measurewords) vm.runInNewContext(fs.readFileSync(path.join(ROOT, file), 'utf8'), context, { filename: file });
const data = context.MEASURE_WORDS_DATA;
const items = data.measureWords;
const Pinyin = common.loadPinyin();
const vocab = common.loadSources().flatMap(s => s.items);
const vocabIds = new Set(vocab.map(v => v.id));
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const optionsOf = id => new Set([...(html.match(new RegExp('<select id="' + id + '">([\\s\\S]*?)</select>')) || ['', ''])[1]
  .matchAll(/<option value="([^"]+)"/g)].map(m => m[1]).filter(v => v !== 'all'));
const LEVELS = new Set(profile.levels.concat(profile.extraLevel));
const KINDS = optionsOf('mw-kind-select');
const CATEGORIES = optionsOf('mw-cat-select');
const LEVEL_BUTTONS = new Set([...html.matchAll(/data-mwlevel="([^"]+)"/g)].map(m => m[1]).filter(v => v !== 'all'));
// Classifiers vocab nouns list that deliberately have no entry (settled 2026-10-11).
const NO_ENTRY = { '曲': 'no classifier sense in CC-CEDICT or HanDeDict (音乐)' };

const errors = [];
const fail = (id, message) => errors.push(id + ': ' + message);

const ids = new Set();
const legacy = new Map();
for (const m of items) {
  const id = m.id;
  if (typeof id !== 'string' || !/^m:/.test(id)) fail(String(id), 'id must start with m:');
  if (ids.has(id)) fail(id, 'duplicate id');
  ids.add(id);
  if (!m.classifier || !id.startsWith('m:' + m.classifier)) fail(id, 'id does not match classifier ' + m.classifier);
  if (!m.pinyin) fail(id, 'no pinyin');
  if (!LEVELS.has(m.level) || !LEVEL_BUTTONS.has(m.level)) fail(id, 'level without filter button: ' + m.level);
  if (!KINDS.has(m.kind)) fail(id, 'kind not in mw-kind-select: ' + m.kind);
  if (m.kindAlso && !KINDS.has(m.kindAlso)) fail(id, 'kindAlso not in mw-kind-select: ' + m.kindAlso);
  if (!CATEGORIES.has(m.category)) fail(id, 'category not in mw-cat-select: ' + m.category);
  if (m.levelSource && !['vocab', 'grammar', 'word'].includes(m.levelSource)) fail(id, 'unknown levelSource ' + m.levelSource);
  if (m.level !== profile.extraLevel && !m.levelSource) fail(id, 'syllabus level without levelSource');
  if (m.table) fail(id, 'counting tables are generated by the app, not stored');
  if (m.vocabId && !vocabIds.has(m.vocabId)) fail(id, 'vocabId does not resolve: ' + m.vocabId);
  for (const noun of m.nouns || []) if (!vocabIds.has(noun)) fail(id, 'noun does not resolve: ' + noun);
  if ((m.nouns || []).length > (m.nounCount || 0)) fail(id, 'nounCount below the listed nouns');
  for (const ex of m.examples || []) {
    if (typeof ex.chinese !== 'string' || typeof ex.german !== 'string') fail(id, 'example without chinese/german');
    else if (!ex.chinese.includes(m.classifier)) fail(id, 'example without the classifier: ' + ex.chinese);
  }
  const german = [m.meaning, m.usage, m.notes, ...(m.examples || []).map(e => e.german), ...(m.specialForms || []).map(s => s.explanation)];
  const umlauts = german.flatMap(asciiUmlauts);
  if (umlauts.length) fail(id, 'ASCII umlauts: ' + umlauts.join(', '));
  for (const old of m.legacyIds || []) {
    if (legacy.has(old)) fail(id, 'legacy id ' + old + ' also on ' + legacy.get(old));
    legacy.set(old, id);
  }
}
for (const [old, id] of legacy) if (ids.has(old)) fail(id, 'legacy id is a live id: ' + old);
for (const [old, target] of Object.entries(data.removed || {})) {
  if (!vocabIds.has(target)) fail('removed ' + old, 'vocab id does not resolve: ' + target);
  if (legacy.has(old)) fail('removed ' + old, 'also a legacy id of ' + legacy.get(old));
}

// Every classifier a noun lists has an entry (reading-aware like the vocabulary detail: 卷 juǎn / juàn).
const byClassifier = new Map();
for (const m of items) { if (!byClassifier.has(m.classifier)) byClassifier.set(m.classifier, []); byClassifier.get(m.classifier).push(m); }
const reads = (m, key) => [m.pinyin, ...(m.pinyinAlt || [])].some(p => Pinyin.toNumeric(p, m.classifier) === key);
for (const v of vocab) {
  for (const mw of v.measureWords || []) {
    if (NO_ENTRY[mw.word]) continue;
    const same = byClassifier.get(mw.word) || [];
    if (!same.length) fail(v.id, 'classifier without entry: ' + mw.word);
    else if (same.length > 1 && !same.some(m => reads(m, mw.pinyin))) fail(v.id, 'no entry for the reading ' + mw.word + ' ' + mw.pinyin);
  }
}

// Campaign ledger (scripts/measure-words/ledger.json, written by scripts/measure-words/apply.cjs): every reviewed/authored entry
// matches its recorded content hash, drafts have no record. Drafts stay allowed while the campaign runs; set
// CAMPAIGN_COMPLETE once all batches are applied, then no draft may remain.
const CAMPAIGN_COMPLETE = false;
const { checkLedger } = require('./enrich/section-campaign.cjs');
const ledger = checkLedger(items, path.join(__dirname, 'measure-words', 'ledger.json'), require('./measure-words/section.cjs').HASH_FIELDS, { requireComplete: CAMPAIGN_COMPLETE });
ledger.errors.forEach(e => errors.push(e));

if (errors.length) {
  console.error(errors.length + ' measure-word problems:\n' + errors.slice(0, 80).join('\n'));
  process.exit(1);
}
const count = {};
items.forEach(m => { count[m.level] = (count[m.level] || 0) + 1; });
console.log('Measure-word audit passed: ' + items.length + ' entries (' + Object.entries(count).map(([l, n]) => l + ' ' + n).join(', ') + '), ' +
  items.reduce((s, m) => s + (m.nouns || []).length, 0) + ' noun links, ' + Object.keys(data.removed || {}).length + ' removed; campaign: ' + ledger.counts.reviewed + ' reviewed, ' + ledger.counts.authored + ' authored, ' + ledger.counts.draft + ' draft.');
